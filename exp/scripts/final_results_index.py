#!/usr/bin/env python3
"""Write reports/prism/00_project/FINAL_RESULTS_INDEX.md: one place that points at every result.

Raw benchmark output is large and mostly stays off GitHub, so the index records
what exists, where it lives on this machine, how big it is and what it hashes
to -- enough that a person on another machine can tell whether a copy they were
given is the same evidence, and enough that the numbers in the paper can be
traced back to the run that produced them.
"""
import argparse
import hashlib
import json
import subprocess
import sys
from pathlib import Path


def sha256_file(p, limit=None):
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for c in iter(lambda: f.read(1 << 20), b""):
            h.update(c)
    return h.hexdigest()


def load(p, default=None):
    try:
        return json.loads(Path(p).read_text())
    except Exception:                                   # noqa: BLE001
        return default


def dir_size(p):
    total = n = 0
    for f in Path(p).rglob("*"):
        if f.is_file():
            total += f.stat().st_size
            n += 1
    return total, n


def human(b):
    for unit in ("B", "KiB", "MiB", "GiB", "TiB"):
        if b < 1024 or unit == "TiB":
            return f"{b:.1f} {unit}" if unit != "B" else f"{b} B"
        b /= 1024


def csv_table(path, columns, limit=None):
    """Render a generated CSV as a markdown table, columns in the given order."""
    import csv
    if not Path(path).is_file():
        return [f"_{Path(path).name} not produced_", ""]
    with open(path) as f:
        rows = list(csv.DictReader(f))
    if not rows:
        return [f"_{Path(path).name} is empty_", ""]
    cols = [c for c in columns if c in rows[0]] or list(rows[0])[:8]
    out = ["| " + " | ".join(cols) + " |",
           "| " + " | ".join("---" for _ in cols) + " |"]
    for r in rows[:limit] if limit else rows:
        cells = []
        for c in cols:
            v = r.get(c, "")
            try:
                v = f"{float(v):.4g}"
            except (TypeError, ValueError):
                pass
            cells.append(str(v))
        out.append("| " + " | ".join(cells) + " |")
    return out + [""]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", type=Path, required=True)
    ap.add_argument("--out", type=Path, required=True)
    args = ap.parse_args()
    root = args.root.resolve()
    ev = root / "exp/results/final-evaluation"
    agg = ev / "06-aggregate"

    manifest = load(root / "exp/final_baseline_manifest.json", {})
    tau = load(ev / "02-tau-calibration/FROZEN_TAU.json", {})
    aggm = load(agg / "AGGREGATION_MANIFEST.json", {})
    canon = load(ev / "CANONICAL_WORKLOAD_SHA256.json", {})

    L = ["# Final results index", "",
         "Every artifact behind the Prism baseline comparison, and where it "
         "lives. Generated by `exp/scripts/final_results_index.py`.", "",
         "## Identity", "",
         f"- runtime evaluated: `{manifest.get('final_runtime_sha')}`",
         f"- worktree patch sha256: `{(manifest.get('runtime') or {}).get('worktree_patch_sha256')}`",
         f"- selected tau: **{tau.get('tau')}** (label `{tau.get('tau_label')}`)",
         f"- tau frozen at: {tau.get('frozen_utc')}",
         f"- calibration seeds: {tau.get('calibration_seeds')}; evaluation "
         f"seeds held out: {tau.get('evaluation_seeds_untouched')}",
         f"- canonical workloads: {len(canon)} files, hashes in "
         "`exp/results/final-evaluation/CANONICAL_WORKLOAD_SHA256.json`", ""]

    L += ["## Tau selection", "",
          "Mean Joint-SLO goodput over the held-out seeds; ties within 3% "
          "relative broken by fewer migrated bytes, then fewer migrations, "
          "then higher tau.", "",
          "| tau | seeds | mean Joint-SLO goodput | mean attainment | migrations | migrated bytes |",
          "| --- | --- | --- | --- | --- | --- |"]
    for cand in (tau.get("candidates") or []):
        L.append(f"| {cand['tau_label']} | {','.join(cand.get('seeds', []))} | "
                 f"{cand['mean_joint_slo_goodput']:.4g} | "
                 f"{cand['mean_joint_slo_attainment']:.4g} | "
                 f"{cand['migrations']} | {cand['migrated_bytes']} |")
    L += ["", f"Raw calibration runs: `exp/results/final-evaluation/"
              f"02-tau-calibration/raw/` · table: `calibration_summary.csv`", ""]

    L += ["## Paired comparison", "",
          "Prototype and Final Prism, both run fresh on the identical canonical "
          "workloads, seeds 1-3 averaged per condition.", "",
          "### Overall and by workload kind", ""]
    L += csv_table(agg / "group_improvement.csv",
                   ["scope", "n_prototype", "n_final",
                    "prototype_goodput_req_s", "final_goodput_req_s",
                    "relative_goodput_req_s", "prototype_ttft_p99",
                    "final_ttft_p99", "prototype_tpot_p99", "final_tpot_p99"])
    L += ["### Per condition", ""]
    L += csv_table(agg / "improvement.csv",
                   ["workload", "rate", "prototype_goodput_req_s",
                    "final_goodput_req_s", "relative_goodput_req_s",
                    "prototype_ttft_mean", "final_ttft_mean",
                    "prototype_ttft_p99", "final_ttft_p99",
                    "prototype_tpot_p99", "final_tpot_p99"])

    L += ["## Where the artifacts are", "",
          "| what | path | size | files |", "| --- | --- | --- | --- |"]
    for label, rel in (
            ("calibration raw (this freeze)", "02-tau-calibration/raw"),
            ("calibration raw (earlier attempts, evidence only)",
             "02-tau-calibration"),
            ("prototype 24 runs", "04b-prototype-fresh/raw"),
            ("final Prism 24 runs", "05-final-c/raw"),
            ("aggregation tables", "06-aggregate")):
        p = ev / rel
        if p.is_dir():
            size, n = dir_size(p)
            L.append(f"| {label} | `exp/results/final-evaluation/{rel}` | "
                     f"{human(size)} | {n} |")
    L += ["",
          "Raw server logs and per-request dumps are large; they stay on the "
          "machine and in the backup below rather than on GitHub. Each run "
          "carries its own `VERIFICATION.json`, `ALG2_INTERACTION.json` and "
          "`CLIENT_FD_VALIDATION.json`, which is what the correctness claims "
          "rest on.", ""]

    manifest_raw = load(ev / "RAW_ARTIFACT_MANIFEST.json")
    if manifest_raw:
        L += ["## Raw artifact manifest", "",
              "`exp/results/final-evaluation/RAW_ARTIFACT_MANIFEST.json` records "
              "the per-run paths and hashes.", ""]

    backup = load(ev / "ARCHIVE_MANIFEST.json")
    if backup:
        L += ["## Archive", "",
              f"- archive: `{backup.get('archive')}`",
              f"- sha256: `{backup.get('sha256')}`",
              f"- size: {human(backup.get('size_bytes', 0))}",
              f"- created: {backup.get('created_utc')}", ""]
    else:
        L += ["## Archive", "",
              "_no archive recorded; run `exp/scripts/final_archive_raw.sh` "
              "before releasing the server_", ""]

    L += ["## Completeness", "",
          f"- prototype runs: {aggm.get('prototype_runs')} / "
          f"{aggm.get('expected_prototype_runs')}",
          f"- final runs: {aggm.get('final_runs')} / "
          f"{aggm.get('expected_final_runs')}",
          f"- aggregation generated: {aggm.get('generated_utc')}", ""]

    args.out.write_text("\n".join(L))
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
